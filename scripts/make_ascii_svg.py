def build_svg():
    lines = ASCII_ART.split('\n')
    line_height = 12
    char_width = 7.2 # Approx monospace char width at 12px
    max_len = max(len(line) for line in lines)
    
    width = max_len * char_width + 40
    height = len(lines) * line_height + 40

    svg = []
    svg.append(f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">')
    svg.append('<style>')
    svg.append('  .ascii-text { font-family: ui-monospace, SFMono-Regular, Menlo, Consolas, monospace; font-size: 12px; fill: #c9d1d9; white-space: pre; }')
    svg.append('  .wipe { animation: wipe-in 0.8s steps(80, end) forwards; opacity: 0; }')
    svg.append('  @keyframes wipe-in {')
    svg.append('      0% { clip-path: inset(0 100% 0 0); opacity: 1; }')
    svg.append('      100% { clip-path: inset(0 0 0 0); opacity: 1; }')
    svg.append('  }')
    svg.append('</style>')
    
    svg.append('<rect width="100%" height="100%" fill="#0d1117" rx="6"/>')
    svg.append('<g transform="translate(20, 30)">')

    # Base animation delay
    delay_per_line = 0.08
    
    for i, line in enumerate(lines):
        # Escape HTML chars if any (none in this specific art, but good practice)
        safe_line = line.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
        delay = i * delay_per_line
        y_pos = i * line_height
        
        svg.append(f'  <text x="0" y="{y_pos}" class="ascii-text wipe" style="animation-delay: {delay}s;">{safe_line}</text>')

    svg.append('</g>')
    svg.append('</svg>')

    out_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../output")
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "avi-ascii.svg")
    
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(svg))
    print(f"avi-ascii.svg generated successfully at {out_path}!")

if __name__ == "__main__":
    build_svg()
